"use strict";
/**
 * Vendor the Markdown parser Ask Nereus renders its answers with.
 *
 *   node server/scripts/vendor-markdown.js [path to markdown-parser]
 *   node server/scripts/vendor-markdown.js --check [path]
 *
 * scripts/md-to-html.js is GENERATED: never edit it by hand. To update it,
 * pull the parser's checkout and run this again.
 *
 * Same arrangement as nereus-sentry-client/tools/vendor-markdown.mjs: the
 * parser's own file, byte for byte, between a provenance header and one
 * `export` line. Keeping the two sites on one parser is the point — an
 * answer that renders one way in Ask Nereus should render the same way
 * here.
 *
 * Its output is NOT trusted as written. scripts/markdown.js rebuilds every
 * tag from an allowlist before any of it reaches the page.
 */

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "../..");
const OUT = path.join(ROOT, "scripts", "md-to-html.js");

const args = process.argv.slice(2);
const check = args.includes("--check");
const given = args.find(a => !a.startsWith("--"));

const candidates = given
  ? [path.resolve(given)]
  : [
      path.resolve(ROOT, "../../Nereus/markdown-parser"),
      path.resolve(ROOT, "../markdown-parser"),
    ];

const repo = candidates.find(d => fs.existsSync(path.join(d, "mdToHtml.min.js")));
if (!repo) {
  console.error(`No markdown-parser checkout with mdToHtml.min.js at ${candidates.join(" or ")} — pass its path.`);
  process.exit(1);
}

const src = fs.readFileSync(path.join(repo, "mdToHtml.min.js"), "utf8");
const sha = crypto.createHash("sha256").update(src).digest("hex").slice(0, 16);

const git = (...a) => {
  try { return execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" }).trim() || "unknown"; }
  catch { return "unknown"; }
};

const out = `// GENERATED by server/scripts/vendor-markdown.js — never edit by hand.
//
// The Markdown parser Ask Nereus renders its answers with, so an answer
// reads the same on both sites. Source: markdown-parser/mdToHtml.min.js
//   commit ${git("log", "-1", "--format=%H %cs", "--", "mdToHtml.min.js")}
//   sha256 ${sha} (first 16)
//
// Its output is NOT trusted: scripts/markdown.js rebuilds every tag from an
// allowlist before any of it reaches the page. The parser reads \`katex\`
// when it meets maths and falls back to plain text when the global is
// absent, which on this site it always is.
/* eslint-disable */
${src.replace(/^"use strict";/, "").trim()}

export { mdToHtml };
`;

if (check) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have === out) { console.log("md-to-html.js matches the checkout."); process.exit(0); }
  console.error("md-to-html.js differs from the checkout — re-run without --check.");
  process.exit(1);
}

fs.writeFileSync(OUT, out);
console.log(`Wrote ${path.relative(ROOT, OUT)} — ${(out.length / 1024).toFixed(1)} KB, parser sha256 ${sha}.`);
